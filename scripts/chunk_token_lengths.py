"""W1-16: how long the chunks are in embedding tokens, against the two models' input limits (offline, no endpoint).

Run:  python scripts/chunk_token_lengths.py          # -> eval/results/chunk_token_lengths.{json,md}

Counts every chunk of every variant (data/chunks/chunks_<variant>.jsonl) with the pinned bge-small-en-v1.5
tokenizer ([CLS] and [SEP] included), which counts exactly as the hosted endpoint does and shares its vocabulary
with all-MiniLM-L6-v2. Reported per variant: mean, median, p95 and maximum, and how many chunks exceed 256
tokens (all-MiniLM-L6-v2 silently embeds only the first 256) and 512 (bge-small-en-v1.5's limit: the client
cuts these, EMBED_MAX_INPUT_TOKENS). Exit codes: 0 = written, 2 = chunk files or the tokenizer missing.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.exceptions import FinSightError  # noqa: E402
from retrieval import CHUNKS_DIR  # noqa: E402
from retrieval.chunking import VARIANTS  # noqa: E402
from retrieval.common import chunks_path  # noqa: E402

OUT_DIR = ROOT / "eval" / "results"
LIMITS = {"minilm": 256, "bge": 512}     # all-MiniLM-L6-v2 max_seq_length; bge-small-en-v1.5 / the endpoint
ENCODE_BATCH = 2_048


def lengths(texts: list[str]) -> list[int]:
    from core.tokens import embed_tokenizer
    tok = embed_tokenizer()
    out: list[int] = []
    for i in range(0, len(texts), ENCODE_BATCH):
        out += [len(e.ids) for e in tok.encode_batch(texts[i:i + ENCODE_BATCH])]
    return out


def summary(counts: list[int]) -> dict[str, float | int]:
    ordered = sorted(counts)
    p95 = ordered[min(len(ordered) - 1, int(0.95 * len(ordered)))]
    row: dict[str, float | int] = {"chunks": len(counts), "mean": round(statistics.fmean(counts), 1),
                                   "median": round(float(statistics.median(counts)), 1), "p95": p95, "max": ordered[-1]}
    for limit in LIMITS.values():
        over = sum(c > limit for c in counts)
        row[f"over_{limit}"], row[f"over_{limit}_pct"] = over, round(100 * over / len(counts), 1)
    return row


def markdown(rows: dict[str, dict]) -> str:
    out = ["# Chunk lengths in embedding tokens (W1-16)", "",
           "Counted with the pinned bge-small-en-v1.5 tokenizer, [CLS] and [SEP] included (generated by "
           "`scripts/chunk_token_lengths.py`). all-MiniLM-L6-v2 embeds the first 256 tokens of a chunk; "
           "bge-small-en-v1.5 takes 512 (the client cuts longer chunks before sending).", "",
           "| Variant | Chunks | Mean | Median | p95 | Max | Over 256 | Over 512 |", "|---|---|---|---|---|---|---|---|"]
    for v, r in rows.items():
        out.append(f"| {v} | {r['chunks']:,} | {r['mean']} | {r['median']} | {r['p95']} | {r['max']:,} | "
                   f"{r['over_256']:,} ({r['over_256_pct']}%) | {r['over_512']:,} ({r['over_512_pct']}%) |")
    return "\n".join(out) + "\n"


def main() -> int:
    rows = {}
    try:
        for variant in VARIANTS:
            path = chunks_path(variant, CHUNKS_DIR)
            texts = [json.loads(line)["text"] for line in path.read_text(encoding="utf-8").splitlines() if line]
            rows[variant] = summary(lengths(texts))
            print(f"{variant}: {rows[variant]}", flush=True)
    except (OSError, FinSightError) as err:
        print(f"ERROR: {err}", file=sys.stderr)
        return 2
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "chunk_token_lengths.json").write_text(json.dumps(rows, indent=1) + "\n", encoding="utf-8",
                                                      newline="\n")
    (OUT_DIR / "chunk_token_lengths.md").write_text(markdown(rows), encoding="utf-8", newline="\n")
    print(f"written: {OUT_DIR / 'chunk_token_lengths.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
