"""WP2 spot check (Week 0 exit criterion, W1-10): a fixed random sample of sections for a person to compare with
the SEC filing, written as a worksheet they fill in.

Run:  python scripts/spot_check_sections.py              # -> docs/wp2_spot_check.md (never overwrites it)
      python scripts/spot_check_sections.py --out other.md --seed 7

The sample is 10 sections from 10 different companies (7 from 10-Ks, 3 from 10-Qs), drawn with a fixed seed
from data/sections/sections.jsonl, so anyone can regenerate the same list. Within a company and form a section
is drawn with a chance proportional to its length (as a random passage of the corpus would land in it), so the
check covers the text retrieval searches rather than mostly one-paragraph pointer Items. For each section the worksheet gives
the SEC link, the opening and closing text, and three sentences from the middle to look up in the SEC page, and
the checker records OK or the problem. The checker should be someone who did not write the parser.
Exit codes: 0 = written, 1 = the output exists already (fill that one in, or pass another --out), 2 = no corpus.
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ROOT / "data" / "sections" / "sections.jsonl"
OUT = ROOT / "docs" / "wp2_spot_check.md"
SEED = 10
N_10K, N_10Q = 7, 3
EXCERPT_CHARS = 300
SENTENCES = 3
MIN_SENTENCE_WORDS = 10
# A prose sentence (no table cell): it starts a line or follows a sentence end, and ends at . ! or ? followed by
# white space, so "$4.8 billion", "U.S.", "Securities, Inc." and "Mr." do not end it (W1-10: the first worksheet
# cut four sentences there) and no sentence starts right after them. A sentence that ends in a one-letter
# abbreviation ("Form 10-K.") runs on into the next one, which is still text to find; sentences over 241
# characters are not drawn.
ABBREVIATIONS = ("Inc", "Corp", "Co", "Ltd", "No", "Nos", "vs", "Mr", "Mrs", "Ms", "Dr", "Jr", "Sr", "St", "al")
_NOT_AFTER = "".join(rf"(?<!\b{a})" for a in ABBREVIATIONS)
_NOT_STARTING_AFTER = r"(?<![^A-Za-z][A-Z]\. )" + "".join(rf"(?<!\b{a}\. )" for a in ABBREVIATIONS)
SENTENCE = re.compile(rf"(?m)(?:^|(?<=[.!?] )){_NOT_STARTING_AFTER}[A-Z][^\n|]{{40,240}}?"
                      rf"(?<![^A-Za-z][A-Z]){_NOT_AFTER}[.!?](?=\s|$)")

CHECKS = """For each section, open the SEC link, find the Item, and check:
1. **Boundaries:** the text starts at this Item's heading and ends where the next Item (or the signatures)
   starts; nothing of the next Item is included.
2. **Nothing lost:** each of the three sentences below is in the SEC page, in this Item, in the same order.
3. **Tables:** one table row reads as `label | value | value` with the numbers the SEC page shows.
4. **Clean text:** no table-of-contents block, "Table of Contents" lines, bare page numbers, or running page
   footers and headers (W1-04).
5. **Metadata:** company, form, fiscal year and period, Item and title are right.

Record OK, or the problem (which check, what you saw), in the results table at the end."""


def load(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def sample(docs: list[dict], seed: int = SEED) -> list[dict]:
    """N_10K + N_10Q sections from as many different companies, weighted by length, reproducible for a seed."""
    rng = random.Random(seed)
    tickers = rng.sample(sorted({d["ticker"] for d in docs}), N_10K + N_10Q)
    out = []
    for i, ticker in enumerate(tickers):
        form = "10-K" if i < N_10K else "10-Q"
        pool = sorted((d for d in docs if d["ticker"] == ticker and d["form"] == form), key=lambda d: d["doc_id"])
        out.append(rng.choices(pool, weights=[d["n_chars"] for d in pool])[0])
    return out


def middle_sentences(text: str, seed: int) -> list[str]:
    """Up to SENTENCES prose sentences from the middle half of the text, in text order."""
    lo, hi = len(text) // 4, 3 * len(text) // 4
    # a sentence must start in the middle half but may end after it (a search cut at `hi` would end "$4." there)
    found = []
    for m in SENTENCE.finditer(text, lo):
        if m.start() >= hi:
            break
        if len(m.group().split()) >= MIN_SENTENCE_WORDS:
            found.append(m.group().strip())
    if len(found) <= SENTENCES:
        return found
    return [found[i] for i in sorted(random.Random(seed).sample(range(len(found)), SENTENCES))]


def fence(text: str) -> str:
    return "```text\n" + text.strip() + "\n```"


def worksheet(picked: list[dict], seed: int) -> str:
    lines = ["# WP2 spot check: sections against the SEC filings", "",
             f"Generated by `scripts/spot_check_sections.py` (seed {seed}) from `data/sections/sections.jsonl`: "
             f"{len(picked)} sections from {len(picked)} companies ({N_10K} from 10-Ks, {N_10Q} from 10-Qs). Week 0 "
             "exit criterion for WP2 (docs/week0_plan.txt), carried over to W1-10.", "",
             "**Checked by:** (name, not the parser's author) · **Date:** (date) · **Corpus:** after W1-04 (ADR-023)",
             "", CHECKS, ""]
    for n, d in enumerate(picked, start=1):
        text = d["text"]
        lines += [f"## {n}. `{d['doc_id']}`", "",
                  f"- {d['ticker']} {d['form']} fiscal {d['fiscal_year']} {d['fiscal_period']}, {d['item']}: "
                  f"{d['item_title']} ({d['n_chars']:,} characters; from the {d['source_location']})",
                  f"- SEC: {d['source_url']}", ""]
        if len(text) <= 2 * EXCERPT_CHARS:
            lines += ["Whole text:", "", fence(text), ""]
        else:
            lines += ["Opening:", "", fence(text[:EXCERPT_CHARS]), "", "Closing:", "", fence(text[-EXCERPT_CHARS:]), ""]
        lines += ["Sentences to find in the SEC page:", ""]
        lines += [f"{i}. {s}" for i, s in enumerate(middle_sentences(text, seed + n), start=1)] or ["(none)"]
        lines.append("")
    lines += ["## Results", "", "| # | Section | Result (OK, or the check that failed and what you saw) |",
              "|---|---|---|"]
    lines += [f"| {n} | `{d['doc_id']}` |  |" for n, d in enumerate(picked, start=1)]
    lines += ["", "**Summary:** (how many OK; any problem found and the ticket that fixes it)", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sections", type=Path, default=SECTIONS)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--seed", type=int, default=SEED)
    args = ap.parse_args(argv)
    if not args.sections.exists():
        print(f"ERROR: {args.sections} not found; build the corpus first (ingest/02_parse_sections.py)",
              file=sys.stderr)
        return 2
    if args.out.exists():
        print(f"ERROR: {args.out} exists; fill that one in (or pass another --out)", file=sys.stderr)
        return 1
    picked = sample(load(args.sections), args.seed)
    args.out.write_text(worksheet(picked, args.seed), encoding="utf-8", newline="\n")
    print(f"{len(picked)} sections -> {args.out}")
    for d in picked:
        print(f"   {d['doc_id']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
