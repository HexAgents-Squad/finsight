"""W1-16: compare two embedding models' retrieval runs on the gold questions, question by question (offline).

Run:  python scripts/compare_embedding_runs.py      # -> eval/results/embedding_comparison.{json,md}

Inputs are run files written by eval/run_retrieval.py: the committed all-MiniLM-L6-v2 runs (eval/results/runs/,
the index ADR-013 built) and the bge-small-en-v1.5 runs (eval/results/embedding_comparison/runs_bge/, from a C3
index built through the hosted endpoint with EMBED_MAX_INPUT_TOKENS=512). For C3 dense and hybrid, with and
without the company+year filters, it reports recall@1/5/10 and MRR for each model (eval/retrieval_eval.py) and
a paired comparison of recall@5 per question: how many questions each model does better on, and a two-sided
sign test on those (ties dropped), because two means 0.03 apart on 73 questions can be two questions.
Exit codes: 0 = written, 2 = a run file or the gold set is missing.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from eval.retrieval_eval import hit_key, recall_at_k, score_runs  # noqa: E402
from eval.validate_gold import DEFAULT_PATH as GOLD_FILE  # noqa: E402
from eval.validate_gold import validate_file  # noqa: E402

RESULTS = ROOT / "eval" / "results"
MODELS = {"all-MiniLM-L6-v2": RESULTS / "runs", "bge-small-en-v1.5": RESULTS / "embedding_comparison" / "runs_bge"}
SETTINGS = [("C3", r, f) for r in ("dense", "hybrid") for f in ("none", "company_year")]
PAIRED_K = 5


def load_run(path: Path) -> dict[str, list]:
    return {r["id"]: [hit_key(x) for x in r["retrieved"]]
            for r in (json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip())}


def sign_test(wins: int, losses: int) -> float:
    """Two-sided exact binomial (p = 0.5) on the questions where the two models differ."""
    n = wins + losses
    if n == 0:
        return 1.0
    tail = sum(math.comb(n, i) for i in range(min(wins, losses) + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def compare(items: list, a: dict[str, list], b: dict[str, list], k: int = PAIRED_K) -> dict[str, float | int]:
    """Questions where b's recall@k is higher, lower or equal than a's, and the sign test on the first two."""
    wins = losses = ties = 0
    for item in items:
        gold = [s.key() for s in item.gold_sources]
        ra, rb = recall_at_k(a.get(item.id, []), gold, k), recall_at_k(b.get(item.id, []), gold, k)
        wins, losses, ties = wins + (rb > ra), losses + (rb < ra), ties + (rb == ra)
    return {"better": wins, "worse": losses, "same": ties, "sign_test_p": round(sign_test(wins, losses), 4)}


def main() -> int:
    rep = validate_file(GOLD_FILE)
    items = [i for i in rep.items if i.gold_sources]
    rows = []
    try:
        for variant, retriever, filters in SETTINGS:
            name = f"{variant}_{retriever}_{filters}.jsonl"
            runs = {m: load_run(d / name) for m, d in MODELS.items()}
            scores = {m: score_runs(rep.items, r)["overall"] for m, r in runs.items()}
            (a_name, a), (b_name, b) = runs.items()
            rows.append({"variant": variant, "retriever": retriever, "filters": filters.replace("_", "+"),
                         "scores": scores, "paired_recall_at_5": compare(items, a, b)})
    except OSError as err:
        print(f"ERROR: {err}", file=sys.stderr)
        return 2
    names = list(MODELS)
    out = ["# Embedding model comparison on the gold questions (W1-16)", "",
           f"{len(items)} gold questions with sources, C3 chunks, the same harness (eval/run_retrieval.py) and filters. "
           f"Generated by `scripts/compare_embedding_runs.py`; decision in ADR-021.", "",
           f"| Retriever | Filters | {names[0]} r@1 / r@5 / r@10 / MRR | {names[1]} r@1 / r@5 / r@10 / MRR | "
           f"r@5 better / worse / same | sign test p |", "|---|---|---|---|---|---|"]
    for r in rows:
        cells = [" / ".join(f"{r['scores'][m][key]:.3f}" for key in ("recall@1", "recall@5", "recall@10", "mrr"))
                 for m in names]
        p = r["paired_recall_at_5"]
        out.append(f"| {r['retriever']} | {r['filters']} | {cells[0]} | {cells[1]} | "
                   f"{p['better']} / {p['worse']} / {p['same']} | {p['sign_test_p']} |")
    out += ["", f"'better' / 'worse': questions where {names[1]} has a higher / lower recall@5 than {names[0]}."]
    (RESULTS / "embedding_comparison.json").write_text(json.dumps(rows, indent=1) + "\n", encoding="utf-8",
                                                       newline="\n")
    (RESULTS / "embedding_comparison.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
